import pandas as pd
df = pd.read_parquet("legi.parquet")
m = df[df.texte_titre.str.strip().str.lower()=="code du travail"].copy()
print(m.article_etat.value_counts().to_dict())
print("date_debut range:", m.date_debut.min(), m.date_debut.max(), "| date_fin values:", m.date_fin.value_counts().head(3).to_dict())
m["ctx_w"] = m.texte_contexte.fillna("").str.split().str.len()
print("context words:", m.ctx_w.describe(percentiles=[.5,.9,.99]).round(1).to_dict())
m["w"] = m.article_contenu_text.str.split().str.len()
print("header/body ratio median:", (m.ctx_w/m.w).median().round(2))
d = m[m.article_contenu_text.duplicated(keep=False)].sort_values("article_contenu_text")
print("dup groups sample:")
for _, r in d.head(6).iterrows(): print("  ", r.article_num, "|", r.article_contenu_text[:70].replace("\n"," "))
print("markdown vs text differ:", (m.article_contenu_markdown != m.article_contenu_text).mean().round(2))
print("prefix split L/R/D:", m.article_num.str[0].value_counts().head(6).to_dict())
long = m[m.w>400]
print("long articles with multiple paragraphs (newline count median):", long.article_contenu_text.str.count("\n").median())
print("long articles sample num:", long.sort_values("w",ascending=False).article_num.head(12).tolist())
print("body has newline fraction:", (m.article_contenu_text.str.contains("\n")).mean().round(2))
print("sample markdown:", repr(m.article_contenu_markdown.iloc[2])[:300])
