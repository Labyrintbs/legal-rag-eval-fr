"""Reader for the VinceGx33/legi-french-law-2025 extract, Code du travail only."""

import collections
import re
import unicodedata
from pathlib import Path

import numpy as np
import pandas as pd
from tokenizers import Tokenizer

from legalrag.models import Article
from legalrag.text import content_hash, normalize_text

DOC_TITLE = "code du travail"
# "R*3231-4" is a real decree article (star = number kept from an older numbering), not an annex.
CODE_NUM = re.compile(r"^[LRD]\*?\d")


def read(parquet_path: Path) -> pd.DataFrame:
    df = pd.read_parquet(parquet_path)
    # Exact match: "contains" would also return laws that merely mention the code.
    return df[df.texte_titre.str.strip().str.lower() == DOC_TITLE].reset_index(drop=True)


def to_articles(m: pd.DataFrame) -> list[Article]:
    articles = []
    for r in m.itertuples():
        num = r.article_num.strip()
        body = normalize_text(r.article_contenu_text)
        articles.append(
            Article(
                uid=f"code_travail:fr:{r.article_id}",
                source_code="code_travail",
                lang="fr",
                kind="article" if CODE_NUM.match(num) else "annex",
                native_id=r.article_id,
                article_num=num,
                section_path=r.texte_contexte,
                body_text=body,
                valid_from=r.date_debut,
                valid_to=r.date_fin,
                status=r.article_etat,
                content_hash=content_hash(body),
                source_url=f"https://www.legifrance.gouv.fr/codes/article_lc/{r.article_id}",
            )
        )
    return articles


def _pct(a: np.ndarray) -> dict[int, int]:
    return {k: int(np.percentile(a, k)) for k in (50, 90, 95, 99)}


def _odd_chars(texts: pd.Series) -> dict[str, int]:
    """Count characters that are invisible or non-standard whitespace."""
    counts: collections.Counter[str] = collections.Counter()
    for t in texts:
        for ch in set(t):
            cat = unicodedata.category(ch)
            if cat in ("Cf", "Cc") and ch not in "\n\t" or (cat == "Zs" and ch != " "):
                counts[f"U+{ord(ch):04X} {unicodedata.name(ch, '?')}"] += 1
    return dict(counts)


def profile(m: pd.DataFrame, tokenizer_path: Path, total_rows: int) -> str:
    tk = Tokenizer.from_file(str(tokenizer_path))

    def n(s: str) -> int:
        return len(tk.encode(s, add_special_tokens=False).ids)

    body = m.article_contenu_text
    tb = np.array([n(s) for s in body])
    words = body.str.split().str.len()
    parts = m.texte_contexte.fillna("").str.split(" > ")
    levels = parts.str.len()

    def tail(p: str, k: int) -> str:
        return " > ".join(p.split(" > ")[-k:])

    h_label = [f"Code du travail, article {a}." for a in m.article_num]
    h_last2 = [
        f"Code du travail, article {a}. {tail(p, 2)}."
        for a, p in zip(m.article_num, m.texte_contexte.fillna(""))
    ]
    h_full = [
        f"Code du travail, article {a}. {p}."
        for a, p in zip(m.article_num, m.texte_contexte.fillna(""))
    ]
    th = {k: np.array([n(s) for s in v]) for k, v in
          {"label": h_label, "last 2": h_last2, "full": h_full}.items()}

    dup_bodies = int(body.duplicated(keep=False).sum())
    num = m.article_num.str.strip()
    first = num.str[0]
    annex = ~num.str.match(CODE_NUM)

    lines = [
        "# Data profile: Code du travail (VinceGx33 extract)",
        "",
        f"Generated by `legalrag.sources.legi.profile`. Rows in file: {total_rows:,}.",
        "",
        "## Rows and columns",
        f"- Rows after filter `texte_titre == 'code du travail'`: {len(m):,}",
        f"- `article_etat`: {m.article_etat.value_counts().to_dict()}",
        f"- `texte_nature`: {m.texte_nature.value_counts().to_dict()}",
        f"- `date_debut`: {m.date_debut.min()} to {m.date_debut.max()}",
        f"- `date_fin` values: {m.date_fin.value_counts().to_dict()}",
        f"- Duplicate `article_id`: {int(m.article_id.duplicated().sum())}",
        f"- Empty bodies: {int((body.str.strip() == '').sum())}",
        f"- Articles whose body is shared with another article: {dup_bodies} rows in "
        f"{body[body.duplicated(keep=False)].nunique()} groups ({int(body.duplicated().sum())} "
        "extra copies)",
        f"- `article_num` first letter after strip: {first.value_counts().to_dict()}",
        f"- `article_num` with leading/trailing whitespace: {int((m.article_num != num).sum())}",
        f"- `article_num` with a star (R*...): {int(num.str.contains(r'\*').sum())}",
        f"- Annex (`article_num` not L/R/D + optional star + digit): {int(annex.sum())}: "
        f"{sorted(set(num[annex]))}",
        f"- Markdown column equal to text column in every row: "
        f"{bool((m.article_contenu_markdown == body).all())}",
        f"- Bodies containing a newline: {int(body.str.contains(chr(10)).sum())}",
        "",
        "## Section path (`texte_contexte`)",
        f"- Empty path: {int((m.texte_contexte.fillna('') == '').sum())}",
        f"- Separator ' > ' consistent (count of '>' = levels - 1): "
        f"{bool((m.texte_contexte.fillna('').str.count('>') == levels - 1).all())}",
        f"- Titles containing '>': {sum(any('>' in x for x in p) for p in parts)}",
        f"- Levels: min {levels.min()}, median {int(levels.median())}, max {levels.max()}",
        f"- Levels distribution: {levels.value_counts().sort_index().to_dict()}",
        "",
        "## Size in bge-m3 tokens (no special tokens)",
        f"- Body percentiles: {_pct(tb)}, mean {int(tb.mean())}, max {int(tb.max())}",
        f"- Tokens per word (median): {float(np.median(tb / words)):.2f}",
        *[f"- Body > {lim}: {int((tb > lim).sum())}" for lim in (256, 512, 1024, 8192)],
        f"- Body < 30: {int((tb < 30).sum())}; < 60: {int((tb < 60).sum())}",
        f"- Header token medians: { {k: int(np.median(v)) for k, v in th.items()} }",
        *[f"- Body + {k} header > 1024: {int(((tb + v) > 1024).sum())}" for k, v in th.items()],
        f"- Total body tokens: {int(tb.sum()):,}; with last-2 header: "
        f"{int((tb + th['last 2']).sum()):,}; with full header: {int((tb + th['full']).sum()):,}",
        "",
        "## Unusual characters (number of rows containing each)",
        f"- Bodies: {_odd_chars(body)}",
        f"- Section paths: {_odd_chars(m.texte_contexte.fillna(''))}",
        "",
    ]
    return "\n".join(lines)
